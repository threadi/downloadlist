<?php
/**
 * File to handle uninstaller-tasks.
 *
 * @package download-list-block-with-icons
 */

namespace DownloadListWithIcons\Plugin;

// prevent direct access.
defined( 'ABSPATH' ) || exit;

use DownloadListWithIcons\Dependencies\easyTransientsForWordPress\Transients;
use WP_Post;
use WP_Query;

/**
 * Object to handle uninstaller-tasks.
 */
class Uninstaller {

	/**
	 * Instance of this object.
	 *
	 * @var ?Uninstaller
	 */
	private static ?Uninstaller $instance = null;

	/**
	 * Constructor for Init-Handler.
	 */
	private function __construct() {}

	/**
	 * Prevent cloning of this object.
	 *
	 * @return void
	 */
	private function __clone() { }

	/**
	 * Return the instance of this Singleton object.
	 */
	public static function get_instance(): Uninstaller {
		if ( is_null( self::$instance ) ) {
			self::$instance = new self();
		}

		return self::$instance;
	}

	/**
	 * Run uninstallation tasks.
	 *
	 * @param bool $uninstall True on real uninstallation, false if the plugin is only reset (keeps the download lists).
	 *
	 * @return void
	 */
	public function run( bool $uninstall = true ): void {
		global $wpdb;

		// register our taxonomies, as the plugin is not loaded during uninstallation.
		Taxonomies::get_instance()->register();

		// delete our own post-type-entries.
		$query = array(
			'post_type'      => 'dl_icons',
			'post_status'    => array( 'any', 'trash' ),
			'posts_per_page' => -1,
			'fields'         => 'ids',
		);
		$posts = new WP_Query( $query );
		foreach ( $posts->get_posts() as $post_id ) {
			if ( $post_id instanceof WP_Post ) {
				continue;
			}
			$post_id = absint( $post_id );

			// get the assigned media-file.
			$attachment_id = absint( get_post_meta( $post_id, 'icon', true ) );

			// remove the image-sizes generated by this plugin from the image.
			if ( $attachment_id > 0 ) {
				$attachment_meta = wp_get_attachment_metadata( $attachment_id );
				$attached_file   = get_attached_file( $attachment_id );
				// remove our sizes from the meta data and the files of these sizes.
				if ( $attachment_meta ) {
					if ( ! empty( $attachment_meta['sizes'] ) ) {
						foreach ( $attachment_meta['sizes'] as $name => $size ) {
							if ( str_contains( $name, 'downloadlist-icon-' ) ) {
								// delete the file of this size, if it is not used by another size.
								if ( is_string( $attached_file ) && ! empty( $size['file'] ) && ! $this->is_file_used_by_other_size( $attachment_meta['sizes'], $name, $size['file'] ) ) {
									wp_delete_file( trailingslashit( dirname( $attached_file ) ) . wp_basename( $size['file'] ) );
								}
								unset( $attachment_meta['sizes'][ $name ] );
							}
						}
					}
					// save the updated meta data.
					wp_update_attachment_metadata( $attachment_id, $attachment_meta );
				}
			}

			// delete the entry.
			wp_delete_post( $post_id, true );
		}

		// delete all terms of our taxonomies (with their meta data and relationships).
		$taxonomies = array( 'dl_icon_set' );
		if ( $uninstall ) {
			// the download lists are only deleted on uninstallation, not on reset.
			$taxonomies[] = 'dl_icon_lists';
		}
		foreach ( $taxonomies as $taxonomy ) {
			$terms = get_terms(
				array(
					'taxonomy'   => $taxonomy,
					'hide_empty' => false,
				)
			);
			if ( is_array( $terms ) ) {
				foreach ( $terms as $term ) {
					wp_delete_term( $term->term_id, $taxonomy );
				}
			}

			// cleanup options from our taxonomy.
			delete_option( $taxonomy . '_children' );
			clean_taxonomy_cache( $taxonomy );
		}

		// get the filesystem handler.
		$wp_filesystem = Helper::get_wp_filesystem();

		// delete style-file.
		$path = Helper::get_style_path();
		if ( $wp_filesystem->exists( $path ) ) {
			$wp_filesystem->delete( $path );
		}

		// get media files with title and/or description to delete these entries.
		$query = array(
			'post_type'      => 'attachment',
			'post_status'    => array( 'any', 'trash' ),
			'posts_per_page' => -1,
			'fields'         => 'ids',
			'meta_query'     => array( // phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_query -- Necessary meta lookup.
				'relation' => 'OR',
				array(
					'key'     => 'dl_title',
					'compare' => 'EXISTS',
				),
				array(
					'key'     => 'dl_description',
					'compare' => 'EXISTS',
				),
			),
		);
		$posts = new WP_Query( $query );
		foreach ( $posts->get_posts() as $post_id ) {
			if ( $post_id instanceof WP_Post ) {
				continue;
			}
			delete_post_meta( absint( $post_id ), 'dl_title' );
			delete_post_meta( absint( $post_id ), 'dl_description' );
		}

		// delete transients (set the slug, as the configuration does not run during uninstallation).
		$transients_obj = Transients::get_instance();
		$transients_obj->set_slug( 'downloadlist' );
		foreach ( $transients_obj->get_transients() as $transient_obj ) {
			// delete transient-data.
			$transient_obj->delete();
		}

		// delete the marker for the tries to generate the style file.
		delete_transient( 'downloadlist_css_generation_tried' );

		// delete all dismiss-marker of our transients.
		$wpdb->query( $wpdb->prepare( 'DELETE FROM ' . $wpdb->options . ' WHERE option_name LIKE %s', $wpdb->esc_like( 'downloadlist-dismissed-' ) . '%' ) ); // phpcs:ignore WordPress.DB.DirectDatabaseQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Direct access necessary for uninstallation.
		wp_cache_delete( 'alloptions', 'options' );

		// delete options.
		$options = array(
			'downloadlistVersion',
			'downloadlist_inheriting_count',
			'downloadlist_inheriting_max',
			'downloadlist_inheriting_status',
			'downloadlist_inheriting_running',
			'downloadlist_download_button_browser_target',
			'downloadlist_update_running',
			DL_TRANSIENT_LIST,
		);
		foreach ( $options as $option ) {
			delete_option( $option );
		}

		// enable the settings.
		$settings_obj = Settings::get_instance();
		$settings_obj->add_settings();
		$settings_obj->get_settings_obj()->activation();
		// and remove them.
		$settings_obj->get_settings_obj()->delete_settings();
	}

	/**
	 * Return whether the given file is used by another size than the given one.
	 *
	 * @param array<string,mixed> $sizes List of sizes from the attachment metadata.
	 * @param string              $size_name The name of the size to ignore.
	 * @param string              $file The file name.
	 *
	 * @return bool
	 */
	private function is_file_used_by_other_size( array $sizes, string $size_name, string $file ): bool {
		foreach ( $sizes as $name => $size ) {
			if ( $name === $size_name || ! is_array( $size ) || empty( $size['file'] ) ) {
				continue;
			}
			if ( $file === $size['file'] && ! str_contains( (string) $name, 'downloadlist-icon-' ) ) {
				return true;
			}
		}
		return false;
	}
}
