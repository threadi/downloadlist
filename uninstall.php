<?php
/**
 * Tasks to run during uninstallation of this plugin.
 *
 * @package download-list-block-with-icons
 */

// Exit if accessed directly.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

// if uninstall.php is not called by WordPress, die.
if ( ! defined( 'WP_UNINSTALL_PLUGIN' ) ) {
	die;
}

// do nothing if PHP-version is not 8.2 or newer.
if ( PHP_VERSION_ID < 80200 ) { // @phpstan-ignore smaller.alwaysFalse
	return;
}

use DownloadListWithIcons\Plugin\Uninstaller;

// save the plugin-path (the main plugin file, like in the plugin itself).
const DL_PLUGIN = __DIR__ . '/download-list-block-with-icons.php';

// save the plugin-version.
const DL_VERSION = '@@VersionNumber@@';

// save transient-list-name.
const DL_TRANSIENT_LIST = 'downloadlist_transients';

// bail if the autoloader is missing (e.g. an incomplete installation).
if ( ! file_exists( __DIR__ . '/vendor/autoload.php' ) ) {
	return;
}

// get autoloader generated by composer.
require_once __DIR__ . '/vendor/autoload.php';

// run uninstaller, in a multisite for every site.
if ( is_multisite() ) {
	foreach ( get_sites(
		array(
			'fields' => 'ids',
			'number' => 0,
		)
	) as $downloadlist_blog_id ) {
		switch_to_blog( absint( $downloadlist_blog_id ) );
		Uninstaller::get_instance()->run();
		restore_current_blog();
	}
} else {
	Uninstaller::get_instance()->run();
}
